'use client';

import { useState } from 'react';
import { motion } from 'framer-motion';
import { PALETTES } from '@/config/palettes';
import { LockupSlide } from '@/features/studio/components/slides/lockup-slide';
import type { LockupLayout } from '@/features/studio/lockup-layout';
import type { PaletteColor } from '@/features/studio/types';

/** Marks generated in Studio, shown in the same lockup slide the product renders. */
const SAMPLES = [
  { name: 'Tidepool', markUrl: 'https://pub-3cb2c9b025f644669c496b633a36faba.r2.dev/studio/doGS6BtxlHGVw6eQT2z3lL2ue8y0/7f632a2b-941a-4a33-aa97-f0bba42166c7.webp', fontName: 'Gabarito', paletteName: 'Seafoam Rest' },
  { name: 'Quiet Art Movement', markUrl: 'https://pub-3cb2c9b025f644669c496b633a36faba.r2.dev/studio/NOJ4jcx2w6bR2DRwT4M3UGDNwpO2/c757a312-0b18-4136-a46a-4f470da4413e.png', fontName: 'Fraunces', paletteName: 'Mauve Serenity' },
  { name: 'Synthetic Clothes', markUrl: 'https://pub-3cb2c9b025f644669c496b633a36faba.r2.dev/studio/NOJ4jcx2w6bR2DRwT4M3UGDNwpO2/4de9c573-4f05-43de-b5e4-5dc2c7d7be2a.png', fontName: 'Tektur', paletteName: 'Turbo Charge' },
];

const LAYOUTS: LockupLayout[] = ['horizontal', 'stacked', 'mark'];

function paletteColors(name: string): PaletteColor[] | undefined {
  const p = PALETTES.find(x => x.name === name);
  if (!p) return undefined;
  return (Object.keys(p.colors) as PaletteColor['role'][]).map(role => ({ role, hex: p.colors[role], name: role }));
}

function SampleCard({ sample, delay }: { sample: (typeof SAMPLES)[number]; delay: number }) {
  const [i, setI] = useState(0);
  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true }}
      transition={{ duration: 0.6, delay }}
      className="space-y-2"
    >
      <div className="relative aspect-video overflow-hidden rounded-xl border bg-white">
        <LockupSlide
          markUrl={sample.markUrl}
          name={sample.name}
          fontName={sample.fontName}
          palette={paletteColors(sample.paletteName)}
          layout={LAYOUTS[i]}
          onNext={() => setI(n => (n + 1) % LAYOUTS.length)}
        />
      </div>
      <p className="text-xs text-muted-foreground">
        {sample.name} · {sample.fontName} · {sample.paletteName}
      </p>
    </motion.div>
  );
}

export function SampleLockups() {
  return (
    <div className="w-full space-y-8">
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        whileInView={{ opacity: 1, y: 0 }}
        viewport={{ once: true }}
        transition={{ duration: 0.6 }}
        className="text-center space-y-4"
      >
        <h2 className="text-3xl md:text-5xl font-black tracking-tight">Made in Studio</h2>
        <p className="text-xl text-muted-foreground max-w-2xl mx-auto">
          Marks generated by Colater, set in their brand font and palette. Click one to change the layout.
        </p>
      </motion.div>
      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
        {SAMPLES.map((s, i) => <SampleCard key={s.markUrl} sample={s} delay={0.1 * i} />)}
      </div>
    </div>
  );
}
